// Generates docs/configuration.md from lib/config-spec.mjs.
//   node scripts/docs-config.mjs                     write the file
//   node scripts/docs-config.mjs --check             exit 1 when the committed file is stale
//   --file <path> overrides the target (used by tests)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { CONFIG_SPEC } from "../lib/config-spec.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const DOCS_PATH = path.join(root, "docs", "configuration.md");

const cell = (s) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

export function generate(spec = CONFIG_SPEC) {
  const rows = [...spec]
    .sort((a, b) => (a.env < b.env ? -1 : a.env > b.env ? 1 : 0))
    .map(
      (e) =>
        "| `" + e.env + "` | " + (e.default === "" ? "unset" : "`" + cell(e.default) + "`") + " | " + cell(e.description) + " |",
    );
  return [
    "# Configuration",
    "",
    "Generated by `pnpm docs:config` from `lib/config-spec.mjs`. Do not edit by hand.",
    "",
    "| Variable | Default | Description |",
    "|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

/** True when `contents` equals what the generator produces, byte for byte. */
export function checkDocs(contents) {
  return contents === generate();
}

function main(argv) {
  const i = argv.indexOf("--file");
  const target = i >= 0 ? path.resolve(argv[i + 1]) : DOCS_PATH;
  if (argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(target, "utf8");
    } catch {}
    if (current === null || !checkDocs(current)) {
      console.error(path.relative(root, target) + " is out of date. Run `pnpm docs:config` and commit the result.");
      process.exit(1);
    }
    return;
  }
  writeFileSync(target, generate());
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
