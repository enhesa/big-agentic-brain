#!/usr/bin/env node
// Deterministic expander for distractors-templated.json (no LLM).
// Usage: node evals/fixtures/generators/gen_distractors_templated.mjs > evals/fixtures/distractors-templated.json
// The committed JSON is a frozen artifact; re-run only when intentionally regenerating.
const AREAS = ["CI", "DNS", "VPN", "payroll", "CRM hygiene", "office wifi", "badge access", "expense policy"];
const VERBS = ["requires", "forbids", "defaults to", "logs", "retries"];
const NOUNS = ["ticket", "approval", "runbook", "checklist", "owner"];
const learnings = [];
let n = 0;
for (const area of AREAS) {
  for (const verb of VERBS) {
    for (const noun of NOUNS) {
      n++;
      learnings.push({
        title: `${area}: ${noun} ${verb} a named owner`,
        body: `House rule for ${area}: every ${noun} ${verb} an explicit owner in the team rota. Record the owner handle, not a free-text name. Generated template #${n}.`,
        tags: ["templated", area.toLowerCase().replace(/\s+/g, "-")],
      });
    }
  }
}
process.stdout.write(JSON.stringify({
  learnings,
  note: "Frozen templated distractors. Regenerated by gen_distractors_templated.mjs; do not edit by hand.",
}, null, 2) + "\n");
